def main():
    shutil.copy(SRC, DST)
    d = docx.Document(DST)
    ps = d.paragraphs

    # 1. Абзацы, переписываемые целиком ------------------------------------
    for idx, text, tag in PARA_REWRITES:
        set_text(ps[idx], text, tag)

    # Подпись рис. 7 в теле — по безразмерной версии (совпадает с полосой подписей)
    set_text(ps[145], CAPTIONS[6][0], "P145 подпись рис. 7 -> безразмерная версия")

    # 2. Механические правки тела статьи -----------------------------------
    for idx, old, new, tag in BODY_FIXES:
        replace_in_paragraph(ps[idx], old, new, tag)

    # 3. Перенумерация рисунков по порядку первого упоминания ---------------
    for idx, old, new in FIGURE_REFS:
        replace_in_paragraph(ps[idx], old, new, f"P{idx} {old!r} -> {new.replace(MARK, '')!r}")
    for p in ps:                                   # снятие временного маркера
        for r in p.runs:
            if MARK in r.text:
                r.text = r.text.replace(MARK, "")

    # 4. Раздел «Связанные работы» в конце Введения ------------------------
    head_model = docx.text.paragraph.Paragraph(copy.deepcopy(ps[54]._p), d)   # подзаголовок
    body_model = docx.text.paragraph.Paragraph(copy.deepcopy(ps[47]._p), d)   # абзац тела
    anchor = clone_after(head_model, RELATED_WORK_HEADING, ps[50])
    for para in RELATED_WORK:
        anchor = clone_after(body_model, para, anchor)
    applied.append(f"«Связанные работы»: заголовок + {len(RELATED_WORK)} абзаца после Введения")

    # 4-. Правки по результатам F-критерия (scripts/stress_ftest.py) --------
    for idx, old_s, new_s, tag in FTEST_FIXES:
        replace_in_paragraph(ps[idx], old_s, new_s, tag)
    # описание критерия — в конец «Протокола валидации»
    clone_after(body_model, SIGNIFICANCE_TEXT, ps[72])
    applied.append("Методика: добавлено описание F-критерия значимости")

    # 4a2. Блок «структура обученной метрики»: четыре фигуры -> одна ------
    for idx, text, tag in MAP_STRUCTURE_TEXT:
        set_text(ps[idx], text, tag)
    # подписи к слитым рисункам (прежние 8, 9, 4) больше не нужны;
    # подпись прежнего рис. 5 заменяется на общую
    for idx in (109, 123, 129):
        drop(ps[idx])
    applied.append("Подписи прежних рис. 8, 9, 4 удалены (слиты в новый рис. 5)")
    set_text(ps[134], f"Рис. 5. {MAP_STRUCTURE_CAPTION}",
             "P134 подпись заменена на общую для объединённого рис. 5")

    for idx, old_s, new_s, tag in DANGLING_PANEL_REFS:
        replace_in_paragraph(ps[idx], old_s, new_s, tag)

    # 4b. Терминология масштабов различий ----------------------------------
    # P53 переписывается целиком: там стояло фактически неверное «пороговые
    # и околопороговые», опровергаемое собственным аудитом
    replace_in_paragraph(
        ps[53],
        "COMBVD содержит психофизически измеренные малые (пороговые "
        "и околопороговые) цветовые различия.",
        SCALE_DEFINITION,
        "P53 определение масштабов (COMBVD — не пороговые различия)")
    n_scale = 0
    for para in ps:
        for old_t, new_t in SCALE_TERMS:
            n, offset = 0, 0
            while (offset := _replace_once(para, old_t, new_t, offset)) is not None:
                n += 1
            n_scale += n
    applied.append(f"Терминология масштабов: {n_scale} замен "
                   f"(«пороговые эллипсоиды» сохранены)")


    # 4a. Рис. 2 — схема эксперимента, в начале Методики --------------------
    # ставится сразу после заголовка ОПИСАНИЕ МЕТОДИКИ: рисунок описывает обе
    # стадии сразу и служит планом раздела
    fig_cap_model = docx.text.paragraph.Paragraph(copy.deepcopy(ps[90]._p), d)
    a = clone_after(body_model, METHOD_SCHEME_TEXT, ps[51])
    a = clone_after(body_model, "", a)
    clone_after(fig_cap_model, f"Рис. 2. {METHOD_SCHEME_CAPTION}", a)
    applied.append("Рис. 2 «Схема эксперимента»: вводный абзац + подпись в Методике")

    # 4b. Раздел «Исследуемые модели» в Методике ---------------------------
    for idx, old, new, tag in TABLE_RENUMBER:
        replace_in_paragraph(ps[idx], old, new, f"нумерация таблиц: {tag}")

    cap_model = docx.text.paragraph.Paragraph(copy.deepcopy(ps[84]._p), d)  # подпись таблицы
    tbl_style = d.tables[0].style

    anchor = clone_after(head_model, MODELS_HEADING, ps[53])
    for para in MODELS_TEXT:
        anchor = clone_after(body_model, para, anchor)
    anchor = clone_caption(cap_model, "Табл. 1.", MODELS_TABLE_CAPTION, anchor)

    # таблица создаётся в конце тела, затем переносится на место
    tbl = d.add_table(rows=len(MODELS_TABLE), cols=len(MODELS_TABLE[0]))
    tbl.style = tbl_style
    for r, row in enumerate(MODELS_TABLE):
        for c, val in enumerate(row):
            cell_p = tbl.cell(r, c).paragraphs[0]
            run = cell_p.add_run(val)
            run.font.name = "Times New Roman"
            run.font.size = Pt(12)
            if r == 0:
                run.font.bold = True
    anchor._p.addnext(tbl._tbl)
    # пустой абзац после таблицы (у Table нет ._p, поэтому вставляем по элементу)
    spacer = copy.deepcopy(body_model._p)
    tbl._tbl.addnext(spacer)
    for r_ in docx.text.paragraph.Paragraph(spacer, d).runs:
        r_.text = ""
    applied.append(f"«Исследуемые модели»: заголовок + {len(MODELS_TEXT)} абзацев + "
                   f"табл. 1 ({len(MODELS_TABLE)-1} моделей)")

    # 5. Абзац тела, ошибочно размеченный как Heading 1 --------------------
    ps[53].style = d.styles["Normal"]
    applied.append("P53 стиль Heading 1 -> Normal (абзац тела)")
    # Подзаголовок в стиле соседних (Normal + полужирный)
    ps[52].style = d.styles["Normal"]
    applied.append("P52 стиль Heading 1 -> Normal (как соседние подзаголовки)")
    # Единый стиль заголовков верхнего уровня
    for idx, name in [(44, "ВВЕДЕНИЕ"), (147, "ОБСУЖДЕНИЕ"), (153, "ЗАКЛЮЧЕНИЕ"),
                      (158, "СПИСОК ЛИТЕРАТУРЫ")]:
        ps[idx].style = d.styles["Heading 1"]
        applied.append(f"{name}: стиль -> Heading 1 (единообразие с ОПИСАНИЕ МЕТОДИКИ/РЕЗУЛЬТАТЫ)")

    # 6. Остаточные заглушки шаблона ---------------------------------------
    for idx, tag in [(156, "P156 заглушка «Текст раздела.»"), (142, "P142 случайный символ «ё»"),
                     (236, "P236 инструкция редакции о вставке рисунков"),
                     (237, "P237 инструкция редакции о подписях")]:
        drop(ps[idx])
        applied.append(tag)

    # 7. Список литературы + REFERENCES ------------------------------------
    # Все источники латиницей => по правилам журнала список даётся однократно
    # под двумя заголовками подряд.
    ref_model = copy.deepcopy(ps[165]._p)          # формат реальной библиозаписи
    refs_head_model = copy.deepcopy(ps[181]._p)    # заголовок REFERENCES

    for i in range(159, 198):                      # шаблон обоих списков
        drop(ps[i])

    anchor = ps[158]                               # «СПИСОК ЛИТЕРАТУРЫ»
    head_p = docx.text.paragraph.Paragraph(refs_head_model, anchor._parent)
    anchor._p.addnext(refs_head_model)
    head_p.style = d.styles["Heading 1"]
    anchor = head_p
    applied.append("REFERENCES: заголовок перенесён под СПИСОК ЛИТЕРАТУРЫ (единый список)")

    model_p = docx.text.paragraph.Paragraph(ref_model, d)
    for entry in BIBLIOGRAPHY:
        anchor = clone_after(model_p, entry, anchor)
    applied.append(f"Список литературы: {len(BIBLIOGRAPHY)} записей")

    # 8. Подписи к рисункам -------------------------------------------------
    ps = d.paragraphs
    cap_start = next(i for i, p in enumerate(ps) if p.text.strip() == "Подписи к рисункам")
    ru_model = copy.deepcopy(ps[cap_start + 2]._p)   # «Рис. 1. Подпись к первому рисунку.»
    blank_model = copy.deepcopy(ps[cap_start + 1]._p)

    for p in list(ps[cap_start + 1:]):
        drop(p)

    anchor = ps[cap_start]
    ru_m = docx.text.paragraph.Paragraph(ru_model, d)
    blank_m = docx.text.paragraph.Paragraph(blank_model, d)

    # порядок и номера — по карте перенумерации
    renumbered = [
        (2, f"Рис. 2. {METHOD_SCHEME_CAPTION}",
            f"Fig. 2. {METHOD_SCHEME_CAPTION_EN}"),
        (5, f"Рис. 5. {MAP_STRUCTURE_CAPTION}",
            f"Fig. 5. {MAP_STRUCTURE_CAPTION_EN}"),
    ]
    for old_no, (ru, en) in enumerate(CAPTIONS, start=1):
        if old_no in DROPPED_FIGURES:      # слиты в рис. 5
            continue
        new_no = NEW_FROM_OLD[old_no]
        ru = ru.replace(f"Рис. {old_no}.", f"Рис. {new_no}.", 1)
        en = en.replace(f"Fig. {old_no}.", f"Fig. {new_no}.", 1)
        renumbered.append((new_no, ru, en))
    renumbered.sort(key=lambda t: t[0])
    nums = [n for n, _, _ in renumbered]
    assert nums == sorted(set(nums)) == list(range(1, len(nums) + 1)), \
        f"нумерация подписей не сквозная: {nums}"

    for _, ru, en in renumbered:
        anchor = clone_after(blank_m, "", anchor)
        anchor = clone_after(ru_m, ru, anchor)
        anchor = clone_after(ru_m, en, anchor)
    applied.append(
        f"Подписи к рисункам: {len(renumbered)} × (рус. + англ.), нумерация по порядку упоминания")

    # ---- 9. Синхронизация подписей в теле с полосой подписей --------------
    # Подпись существует в двух местах (по месту в тексте и на отдельной
    # полосе, как требует журнал), и они успели разойтись: правка вносилась
    # в один экземпляр. Переписываем оба из ОДНОГО источника, чтобы
    # расхождение стало невозможным по построению.
    # Поиск по тексту, а не по индексам: вставки разделов сдвигают нумерацию
    # абзацев, и жёсткие индексы указывают не туда.
    ru_by_no = {n: ru for n, ru, _ in renumbered}
    cur = d.paragraphs
    page_start = next(i for i, q in enumerate(cur)
                      if q.text.strip() == "Подписи к рисункам")
    n_sync = 0
    for i, q in enumerate(cur[:page_start]):
        m = re.match(r"^Рис\.\s*(\d+)\.", q.text.strip())
        if not m:
            continue
        no = int(m.group(1))
        if no in ru_by_no and q.text.strip() != ru_by_no[no].strip():
            set_text(q, ru_by_no[no], f"подпись рис. {no} в теле синхронизирована")
            n_sync += 1
    if n_sync == 0:
        applied.append("Подписи в теле уже совпадают с полосой подписей")

    d.save(DST)

    print(f"Применено правок: {len(applied)}")
    for a in applied:
        print("  +", a)
    if missed:
        print(f"\nНЕ НАЙДЕНО: {len(missed)}")
        for m in missed:
            print("  !", m)
    return 1 if missed else 0


if __name__ == "__main__":
    sys.exit(main())
